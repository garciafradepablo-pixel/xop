// Generator: reads the curriculum-i18n workflow output(s) and writes
// src/data/galaxy.curriculum.i18n.ts ({ locale: { constellationId: { code: Lesson } } }).
import fs from 'node:fs';

const SRCS = process.argv.slice(2);
const OUT = new URL('../src/data/galaxy.curriculum.i18n.ts', import.meta.url);
const LOCALES = ['en', 'th', 'fr', 'it', 'ch'];

const decode = (s) => String(s)
  .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&apos;/g, "'");

const lesson = (m) => ({
  objetivo: decode(m.objetivo || ''),
  porque: decode(m.porque || ''),
  leccion: (m.leccion || []).map(decode),
  ejercicio: decode(m.ejercicio || ''),
  entregable: decode(m.entregable || ''),
  insight: decode(m.insight || ''),
  errores: (m.errores || []).map(decode),
});

const overlay = {};
for (const l of LOCALES) overlay[l] = {};
for (const src of SRCS) {
  if (!fs.existsSync(src) || fs.statSync(src).size === 0) { console.warn('skip:', src); continue; }
  const j = JSON.parse(fs.readFileSync(src, 'utf8'));
  const ov = (j.overlay ? j : (j.result || {})).overlay || {};
  for (const loc of Object.keys(ov)) {
    overlay[loc] = overlay[loc] || {};
    for (const cid of Object.keys(ov[loc])) {
      overlay[loc][cid] = overlay[loc][cid] || {};
      for (const code of Object.keys(ov[loc][cid])) overlay[loc][cid][code] = lesson(ov[loc][cid][code]);
    }
  }
}

const header = `// ════════════════════════════════════════════════════════════════════════
// Deep-lesson translations overlay. \`galaxy.curriculum.ts\` holds the ES
// canonical lessons; this file provides en/th/fr/it/ch. \`getLocalizedLesson\`
// returns the translated lesson for a locale, falling back to ES.
//
// GENERATED by scripts/gen-curriculum-i18n.mjs from the curriculum-i18n workflow.
// ════════════════════════════════════════════════════════════════════════
import { curriculum, type Lesson } from './galaxy.curriculum';

export type CurriculumI18n = Record<string, Record<string, Record<string, Lesson>>>;

export const curriculumI18n: CurriculumI18n = `;

const footer = `;

/** Lesson for a module in a given locale; ES (or any missing translation) → canonical. */
export const getLocalizedLesson = (constellationId: string, code: string, locale: string): Lesson | null => {
  if (locale !== 'es') {
    const t = curriculumI18n[locale]?.[constellationId]?.[code];
    if (t) return t;
  }
  return curriculum[constellationId]?.[code] ?? null;
};
`;

fs.writeFileSync(OUT, header + JSON.stringify(overlay, null, 2) + footer, 'utf8');
const report = LOCALES.map((l) => {
  const cids = Object.keys(overlay[l] || {});
  const n = cids.reduce((s, c) => s + Object.keys(overlay[l][c]).length, 0);
  return `${l}: ${n} lessons`;
}).join('\n');
console.log('Wrote galaxy.curriculum.i18n.ts\n' + report);
