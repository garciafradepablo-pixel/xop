// Generator: reads the cabinet-of-sages workflow output and writes
// src/data/galaxy.curriculum.ts ({ constellationId: { code: Lesson } }).
import fs from 'node:fs';

const SRCS = process.argv.slice(2); // one or more workflow outputs; later files override per-module
const OUT = new URL('../src/data/galaxy.curriculum.ts', import.meta.url);

const decode = (s) => String(s)
  .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&apos;/g, "'");

// Merge all sources at the MODULE level (later files add/override modules,
// never wipe a whole constellation).
const clean = {};
for (const src of SRCS) {
  const j = JSON.parse(fs.readFileSync(src, 'utf8'));
  const curriculum = (j.curriculum ? j : (j.result || {})).curriculum || {};
  for (const cid of Object.keys(curriculum)) {
    clean[cid] = clean[cid] || {};
    for (const code of Object.keys(curriculum[cid])) {
      const m = curriculum[cid][code] || {};
      clean[cid][code] = {
        objetivo: decode(m.objetivo || ''),
        porque: decode(m.porque || ''),
        leccion: (m.leccion || []).map(decode),
        ejercicio: decode(m.ejercicio || ''),
        entregable: decode(m.entregable || ''),
        insight: decode(m.insight || ''),
        errores: (m.errores || []).map(decode),
      };
    }
  }
}

const header = `// ════════════════════════════════════════════════════════════════════════
// Master curriculum — deep lessons authored by the "cabinet of sages" (one
// domain expert per constellation). Keyed by constellation id → module code.
// \`galaxy.ts\` holds the structure (title/blurb); this holds the actual teaching.
// A module with no lesson here simply renders its blurb (graceful fallback).
//
// GENERATED by scripts/gen-curriculum.mjs from the cabinet-of-sages workflow.
// ════════════════════════════════════════════════════════════════════════

export interface Lesson {
  objetivo: string;
  porque: string;
  leccion: string[];
  ejercicio: string;
  entregable: string;
  insight: string;
  errores: string[];
}

export type Curriculum = Record<string, Record<string, Lesson>>;

export const curriculum: Curriculum = `;

const footer = `;

/** Returns the lesson for a constellation module, or null if none authored yet. */
export const getLesson = (constellationId: string, code: string): Lesson | null =>
  curriculum[constellationId]?.[code] ?? null;

/** How many modules in a constellation have a full lesson. */
export const lessonCount = (constellationId: string): number =>
  Object.keys(curriculum[constellationId] ?? {}).length;
`;

fs.writeFileSync(OUT, header + JSON.stringify(clean, null, 2) + footer, 'utf8');

const report = Object.entries(clean).map(([cid, mods]) => {
  const paras = Object.values(mods).reduce((n, m) => n + (m.leccion?.length || 0), 0);
  return `${cid}: ${Object.keys(mods).length} lessons, ${paras} paragraphs`;
}).join('\n');
console.log('Wrote galaxy.curriculum.ts\n' + report);
