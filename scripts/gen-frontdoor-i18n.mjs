// Generator: reads the frontdoor-i18n workflow output, writes
// src/data/frontdoor.i18n.ts ({ locale: { page: { es: t } } }) + the frontTr helper.
import fs from 'node:fs';

const SRC = process.argv[2];
const OUT = new URL('../src/data/frontdoor.i18n.ts', import.meta.url);
const PAGES = ['info', 'manifiesto', 'privacidad', 'prompts', 'soporte'];
const LOCALES = ['en', 'th', 'fr', 'it', 'ch'];

const j = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const byLocale = (j.byLocale ? j : (j.result || {})).byLocale;

const decode = (s) => String(s)
  .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&apos;/g, "'");

const out = {};
for (const loc of LOCALES) {
  out[loc] = {};
  const pages = byLocale[loc] || {};
  for (const p of PAGES) {
    out[loc][p] = {};
    for (const pair of (pages[p] || [])) {
      if (pair && pair.es != null) out[loc][p][decode(pair.es)] = decode(pair.t ?? pair.es);
    }
  }
}

const header = `// ════════════════════════════════════════════════════════════════════════
// Front-door page translations (info, manifiesto, privacidad, prompts, soporte).
// Pages keep Spanish inline as canonical; \`frontTr(page, locale)\` looks each
// string up by exact match, falling back to Spanish if missing.
//
// Shape: { <locale>: { <pageId>: { "<es string>": "<translation>" } } }
// GENERATED by scripts/gen-frontdoor-i18n.mjs from the frontdoor-i18n workflow.
// ════════════════════════════════════════════════════════════════════════

export type FrontdoorI18n = Record<string, Record<string, Record<string, string>>>;

export const frontdoorI18n: FrontdoorI18n = `;

const footer = `;

/** Returns tr(esString) for a given page + locale. ES (or any miss) → the original string. */
export function frontTr(page: string, locale: string) {
  const dict = locale === 'es' ? null : frontdoorI18n[locale]?.[page];
  return (s: string): string => (dict && dict[s]) || s;
}
`;

fs.writeFileSync(OUT, header + JSON.stringify(out, null, 2) + footer, 'utf8');

const report = LOCALES.map((l) => `${l}: ` + PAGES.map((p) => `${p}=${Object.keys(out[l][p]).length}`).join(' ')).join('\n');
console.log('Wrote frontdoor.i18n.ts\n' + report);
